from google import genai

# Initialize client — set your API key in Kaggle Secrets as GOOGLE_API_KEY
client = genai.Client(api_key=os.environ.get("GOOGLE_API_KEY", ""))

TRANSLITERATION_PROMPT = """You are a Nepali-English bilingual transcription expert.

Your task: Given a Nepali transcript where English loanwords have been written 
in Devanagari script (transliterated), detect those English words and rewrite 
them in correct English spelling. Leave all Nepali words exactly as they are.

Rules:
1. Only convert words that are clearly English loanwords (cricket, football, 
   academy, coaching, video, etc.)
2. Keep Nepali grammar particles attached to English words as-is 
   (e.g., "cricketमा" stays as "cricketमा", not "cricket मा")
3. Do NOT translate — only restore English spelling
4. Preserve the original word order exactly
5. Return ONLY the corrected transcript, nothing else

Examples:
Input:  म academy wise खेले अ त्यसरी प्रदेशबाट मैले खेलेको तर मैले खेल्नु भन्दा नि म त्यो क्रिकेट भित्र गएर
Output: म academy wise खेले अ त्यसरी प्रदेशबाट मैले खेलेको तर मैले खेल्नु भन्दा नि म त्यो cricket भित्र गएर

Input:  फाइनान्सियल हिसाबले म अलिकति डाउन भएर नसिकाको हो
Output: financial हिसाबले म अलिकति down भएर नसिकाको हो

Now process this transcript:
"""


def transliterate_batch(transcripts: list[str], batch_size: int = 10) -> list[str]:
    """Send transcripts to the LLM in batches and return augmented versions."""
    results = []
    for i in range(0, len(transcripts), batch_size):
        batch = transcripts[i:i + batch_size]
        batch_results = []
        
        for text in batch:
            try:
                response = client.models.generate_content(
                    model="gemini-2.5-flash",
                    contents=TRANSLITERATION_PROMPT + text,
                )
                augmented = response.text.strip()
                # Basic sanity check: result should be roughly same length
                if len(augmented) < len(text) * 0.3 or len(augmented) > len(text) * 3:
                    print(f"  [WARN] Suspicious output length, keeping original")
                    batch_results.append(text)
                else:
                    batch_results.append(augmented)
            except Exception as e:
                print(f"  [ERROR] {e}, keeping original")
                batch_results.append(text)
        
        results.extend(batch_results)
        
        if (i + batch_size) % 500 == 0:
            print(f"  Processed {i + batch_size}/{len(transcripts)}")
        
        time.sleep(0.5)  # rate limit
    
    return results


