# ── Cell 5: Language detection utilities ────────────────────────────────────

def is_english_word(word: str) -> bool:
    """Detect if a word is English (Latin script) vs Nepali (Devanagari).
    
    Handles mixed tokens like 'cricketमा' by checking if the word starts
    with Latin characters.
    """
    # Strip punctuation
    cleaned = re.sub(r'[^\w]', '', word)
    if not cleaned:
        return False
    
    # Check if the first character is Latin (ASCII letter)
    first_char = cleaned[0]
    if first_char.isascii() and first_char.isalpha():
        return True
    
    return False


def extract_english_stem(word: str) -> str:
    """Extract the English portion from mixed tokens like 'cricketमा'.
    
    Returns the leading Latin-script substring.
    """
    match = re.match(r'^([a-zA-Z]+)', word)
    return match.group(1).lower() if match else word.lower()


# ── Cell 6: CS-WER calculation ──────────────────────────────────────────────
from jiwer import process_words, WordOutput

def compute_cs_wer(references: list[str], hypotheses: list[str]) -> dict:
    """Compute Code-Switched Word Error Rate.
    
    Aligns reference and hypothesis word-by-word, then calculates error rate
    strictly over English loanwords in the reference.
    
    Returns:
        dict with keys:
            - overall_wer: standard WER over all words
            - cs_wer: WER isolated to English tokens
            - english_total: total English tokens in reference
            - english_correct: correctly predicted English tokens
            - english_substitutions: substituted English tokens  
            - english_deletions: deleted English tokens
            - nepali_wer: WER over Nepali-only tokens (for comparison)
    """
    
    total_eng = 0
    correct_eng = 0
    sub_eng = 0
    del_eng = 0
    ins_eng = 0  # insertions of spurious English words
    
    total_nep = 0
    correct_nep = 0
    sub_nep = 0
    del_nep = 0
    
    wer_metric = evaluate.load("wer")
    overall_wer = wer_metric.compute(predictions=hypotheses, references=references)
    
    for ref, hyp in zip(references, hypotheses):
        # Use jiwer alignment
        output: WordOutput = process_words(ref, hyp)
        
        for chunk in output.alignments[0]:
            ref_slice = output.references[0][chunk.ref_start_idx:chunk.ref_end_idx]
            hyp_slice = output.hypotheses[0][chunk.hyp_start_idx:chunk.hyp_end_idx]
            
            if chunk.type == "equal":
                for w in ref_slice:
                    if is_english_word(w):
                        total_eng += 1
                        correct_eng += 1
                    else:
                        total_nep += 1
                        correct_nep += 1
                        
            elif chunk.type == "substitute":
                for w in ref_slice:
                    if is_english_word(w):
                        total_eng += 1
                        sub_eng += 1
                    else:
                        total_nep += 1
                        sub_nep += 1
                        
            elif chunk.type == "delete":
                for w in ref_slice:
                    if is_english_word(w):
                        total_eng += 1
                        del_eng += 1
                    else:
                        total_nep += 1
                        del_nep += 1
                        
            elif chunk.type == "insert":
                for w in hyp_slice:
                    if is_english_word(w):
                        ins_eng += 1
    
    cs_wer = (sub_eng + del_eng + ins_eng) / total_eng * 100 if total_eng > 0 else 0.0
    nep_wer = (sub_nep + del_nep) / total_nep * 100 if total_nep > 0 else 0.0
    
    return {
        "overall_wer": round(overall_wer * 100, 2),
        "cs_wer": round(cs_wer, 2),
        "nepali_wer": round(nep_wer, 2),
        "english_total": total_eng,
        "english_correct": correct_eng,
        "english_substitutions": sub_eng,
        "english_deletions": del_eng,
        "english_insertions": ins_eng,
        "nepali_total": total_nep,
    }


# ── Cell 7: Quick sanity check on CS-WER ────────────────────────────────────
def test_cs_wer():
    """Verify the CS-WER metric with a known example."""
    refs = [
        "म cricket खेल्छु र football पनि हेर्छु",
        "हाम्रो team ले match जित्यो"
    ]
    hyps = [
        "म क्रिकेट खेल्छु र football पनि हेर्छु",   # cricket wrong, football correct
        "हाम्रो team ले match हार्यो"                  # team/match correct, जित्यो→हार्यो (nepali error)
    ]
    
    result = compute_cs_wer(refs, hyps)
    print("CS-WER Sanity Check:")
    for k, v in result.items():
        print(f"  {k}: {v}")
    # Expected: cs_wer should reflect 1 error out of 4 English words = 25%

test_cs_wer()


