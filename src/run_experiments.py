# ── Cell 10: Training utilities ─────────────────────────────────────────────
wer_metric = evaluate.load("wer")

def get_compute_metrics_fn(tokenizer):
    def compute_metrics(pred):
        pred_ids = pred.predictions
        label_ids = pred.label_ids
        label_ids[label_ids == -100] = tokenizer.pad_token_id
        pred_str = tokenizer.batch_decode(pred_ids, skip_special_tokens=True)
        label_str = tokenizer.batch_decode(label_ids, skip_special_tokens=True)
        wer = 100 * wer_metric.compute(predictions=pred_str, references=label_str)
        return {"wer": wer}
    return compute_metrics


def train_model(
    dataset,
    output_dir: str,
    constrain_language: bool = True,
    base_model: str = None,
):
    """Train a Whisper model with the given configuration.
    
    Args:
        dataset: preprocessed HuggingFace dataset with train/test splits
        output_dir: where to save checkpoints
        constrain_language: if True, force <|ne|> token; if False, unconstrained
        base_model: model name or path to start from
    """
    if base_model is None:
        base_model = config.BASE_MODEL
    
    feature_extractor = WhisperFeatureExtractor.from_pretrained(base_model)
    tokenizer = WhisperTokenizer.from_pretrained(base_model, language="ne", task="transcribe")
    processor = WhisperProcessor.from_pretrained(base_model, language="ne", task="transcribe")
    model = WhisperForConditionalGeneration.from_pretrained(base_model)
    
    # Generation config — this is the KEY experimental variable
    model.generation_config.task = "transcribe"
    model.generation_config.max_new_tokens = 225
    model.generation_config.no_repeat_ngram_size = 3
    
    if constrain_language:
        # Standard Whisper: force Nepali language token
        model.generation_config.language = "ne"
        model.generation_config.forced_decoder_ids = processor.get_decoder_prompt_ids(
            language="ne", task="transcribe"
        )
        # Default suppress_tokens stays as-is
        print("  Decoder: CONSTRAINED to <|ne|>")
    else:
        # Our approach: unconstrained decoder for code-switching
        model.generation_config.language = None
        model.generation_config.forced_decoder_ids = None
        model.generation_config.suppress_tokens = []
        print("  Decoder: UNCONSTRAINED (code-switching mode)")
    
    data_collator = DataCollatorSpeechSeq2SeqWithPadding(
        processor=processor,
        decoder_start_token_id=model.config.decoder_start_token_id,
    )
    
    training_args = Seq2SeqTrainingArguments(
        output_dir=output_dir,
        per_device_train_batch_size=config.BATCH_SIZE,
        per_device_eval_batch_size=config.BATCH_SIZE,
        gradient_accumulation_steps=config.GRADIENT_ACCUMULATION,
        learning_rate=config.LEARNING_RATE,
        warmup_steps=config.WARMUP_STEPS,
        lr_scheduler_type="linear",
        num_train_epochs=config.NUM_EPOCHS,
        eval_steps=config.EVAL_STEPS,
        save_steps=config.SAVE_STEPS,
        logging_steps=config.LOGGING_STEPS,
        eval_strategy="steps",
        predict_with_generate=True,
        generation_max_length=225,
        fp16=config.FP16,
        dataloader_num_workers=2,
        save_total_limit=2,
        load_best_model_at_end=True,
        metric_for_best_model="wer",
        greater_is_better=False,
        report_to=["tensorboard"],
        push_to_hub=False,
        remove_unused_columns=False,
        label_names=["labels"],
        seed=config.SEED,
    )
    
    trainer = Seq2SeqTrainer(
        args=training_args,
        model=model,
        train_dataset=dataset["train"],
        eval_dataset=dataset["test"],
        data_collator=data_collator,
        compute_metrics=get_compute_metrics_fn(tokenizer),
        processing_class=processor.feature_extractor,
    )
    
    torch.cuda.empty_cache()
    gc.collect()
    
    trainer.train()
    
    # Save final model
    final_path = os.path.join(output_dir, "final-model")
    trainer.save_model(final_path)
    processor.save_pretrained(final_path)
    tokenizer.save_pretrained(final_path)
    
    print(f"Model saved to {final_path}")
    return final_path


# ── Cell 11: Inference function ─────────────────────────────────────────────

def run_inference(
    model_path: str,
    audio_paths: list[str],
    constrain_language: bool = True,
) -> list[str]:
    """Run Whisper inference on a list of audio files.
    
    Args:
        model_path: path to model checkpoint or HF model name
        audio_paths: list of paths to .wav files
        constrain_language: whether to force <|ne|> during decoding
    
    Returns:
        list of predicted transcriptions
    """
    feature_extractor = WhisperFeatureExtractor.from_pretrained(model_path)
    tokenizer = WhisperTokenizer.from_pretrained(model_path, language="ne", task="transcribe")
    processor = WhisperProcessor.from_pretrained(model_path, language="ne", task="transcribe")
    model = WhisperForConditionalGeneration.from_pretrained(model_path)
    model.to("cuda" if torch.cuda.is_available() else "cpu")
    model.eval()
    
    # Set generation config
    if not constrain_language:
        model.generation_config.language = None
        model.generation_config.forced_decoder_ids = None
        model.generation_config.suppress_tokens = []
    
    model.generation_config.max_new_tokens = 225
    model.generation_config.no_repeat_ngram_size = 3
    
    predictions = []
    for path in audio_paths:
        audio, sr = librosa.load(path, sr=config.SAMPLING_RATE)
        inputs = feature_extractor(audio, sampling_rate=sr, return_tensors="pt")
        inputs = inputs.to(model.device)
        
        with torch.no_grad():
            ids = model.generate(inputs.input_features)
        
        text = tokenizer.decode(ids[0], skip_special_tokens=True)
        predictions.append(text)
    
    # Free GPU memory
    del model
    torch.cuda.empty_cache()
    gc.collect()
    
    return predictions


# ── Cell 12: Run the full ablation ──────────────────────────────────────────

