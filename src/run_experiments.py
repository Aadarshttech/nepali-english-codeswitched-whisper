# ── Cell 14: Error analysis ─────────────────────────────────────────────────

def error_analysis(
    references: list[str],
    hypotheses: list[str],
    n_examples: int = 20,
):
    """Qualitative error analysis: categorize failures by CS type.
    
    Categories:
    1. Intra-sentential: single English word inside Nepali sentence
    2. Inter-sentential: whole English phrase/clause
    3. Mixed-morphology: English stem + Nepali suffix (e.g., "cricketमा")
    4. Proper nouns: names, brands, places
    """
    
    categories = {
        "intra_sentential": [],   # single English word errors
        "inter_sentential": [],   # multi-word English phrase errors
        "mixed_morphology": [],   # errors on words like "cricketमा"
        "proper_noun": [],        # person/place name errors
    }
    
    for ref, hyp in zip(references, hypotheses):
        output: WordOutput = process_words(ref, hyp)
        
        for chunk in output.alignments[0]:
            if chunk.type in ("substitute", "delete"):
                ref_words = output.references[0][chunk.ref_start_idx:chunk.ref_end_idx]
                hyp_words = output.hypotheses[0][chunk.hyp_start_idx:chunk.hyp_end_idx]
                
                eng_words = [w for w in ref_words if is_english_word(w)]
                if not eng_words:
                    continue
                
                example = {
                    "reference": " ".join(ref_words),
                    "hypothesis": " ".join(hyp_words) if hyp_words else "[DELETED]",
                    "full_ref": ref,
                    "full_hyp": hyp,
                }
                
                # Classify
                has_devanagari_suffix = any(
                    re.search(r'[a-zA-Z]+[\u0900-\u097F]', w) for w in eng_words
                )
                
                if has_devanagari_suffix:
                    categories["mixed_morphology"].append(example)
                elif len(eng_words) >= 2:
                    categories["inter_sentential"].append(example)
                elif any(w[0].isupper() for w in eng_words if w):
                    categories["proper_noun"].append(example)
                else:
                    categories["intra_sentential"].append(example)
    
    # Print summary
    print("\n" + "=" * 80)
    print("ERROR ANALYSIS: Code-Switching Failure Categories")
    print("=" * 80)
    
    for cat, examples in categories.items():
        print(f"\n{'─' * 60}")
        print(f"Category: {cat.upper()} ({len(examples)} errors)")
        print(f"{'─' * 60}")
        for ex in examples[:n_examples]:
            print(f"  REF: {ex['reference']}")
            print(f"  HYP: {ex['hypothesis']}")
            print()
    
    # Summary counts
    print(f"\n{'─' * 60}")
    print("Summary:")
    total = sum(len(v) for v in categories.values())
    for cat, examples in categories.items():
        pct = len(examples) / total * 100 if total > 0 else 0
        print(f"  {cat}: {len(examples)} ({pct:.1f}%)")
    print(f"  TOTAL: {total}")
    
    return categories


