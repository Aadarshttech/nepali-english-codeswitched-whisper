    references = gold_test_df["transcription"].tolist()
    
    results = {}
    
    # ── Model A: Zero-shot Whisper Small ──
    print("=" * 60)
    print("MODEL A: Zero-shot Whisper Small (baseline)")
    print("=" * 60)
    preds_a = run_inference(config.BASE_MODEL, audio_paths, constrain_language=True)
    results["A: Zero-shot"] = compute_cs_wer(references, preds_a)
    results["A: Zero-shot"]["predictions"] = preds_a
    
    # ── Model B: Finetuned original + constrained ──
    if config.FINETUNED_ORIGINAL:
        print("=" * 60)
        print("MODEL B: Finetuned (original data) + forced <|ne|>")
        print("=" * 60)
        preds_b = run_inference(config.FINETUNED_ORIGINAL, audio_paths, constrain_language=True)
        results["B: FT-Original+Constrained"] = compute_cs_wer(references, preds_b)
        results["B: FT-Original+Constrained"]["predictions"] = preds_b
    
    # ── Model C: Finetuned original + unconstrained ──
    if config.FINETUNED_ORIGINAL:
        print("=" * 60)
        print("MODEL C: Finetuned (original data) + unconstrained")
        print("=" * 60)
        preds_c = run_inference(config.FINETUNED_ORIGINAL, audio_paths, constrain_language=False)
        results["C: FT-Original+Unconstrained"] = compute_cs_wer(references, preds_c)
        results["C: FT-Original+Unconstrained"]["predictions"] = preds_c
    
    # ── Model D: Finetuned augmented + unconstrained (OURS) ──
    if config.FINETUNED_AUGMENTED:
        print("=" * 60)
        print("MODEL D: Finetuned (LLM-augmented) + unconstrained [OURS]")
        print("=" * 60)
        preds_d = run_inference(config.FINETUNED_AUGMENTED, audio_paths, constrain_language=False)
        results["D: FT-Augmented+Unconstrained"] = compute_cs_wer(references, preds_d)
        results["D: FT-Augmented+Unconstrained"]["predictions"] = preds_d
    
    return results


